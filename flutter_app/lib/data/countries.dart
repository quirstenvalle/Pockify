/// Resolves a display symbol from either a modern ISO currency code
/// (e.g. "PHP") or a legacy free-text value stored before country-based
/// currency detection existed (e.g. "PHP (₱)").
String currencySymbolForCurrency(String? currencyValue) {
  if (currencyValue == null || currencyValue.trim().isEmpty) return '₱';

  final trimmed = currencyValue.trim();
  final legacyMatch = RegExp(r'\(([^)]+)\)').firstMatch(trimmed);
  if (legacyMatch != null) {
    return legacyMatch.group(1) ?? '₱';
  }

  final code = trimmed.toUpperCase();
  return kCurrencySymbols[code] ?? '₱';
}
